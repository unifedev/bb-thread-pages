export function formatSubmissionMessage(submission: Submission): string {
  const heading = submission.title.trim() || "Thread Page";
  const fields = submission.answers.map((answer) => {
    const label = answer.label.trim() || answer.name;
    const value = Array.isArray(answer.value)
      ? answer.value.length > 0
        ? answer.value.join(", ")
        : "(left blank)"
      : typeof answer.value === "boolean"
        ? answer.value
          ? "Yes"
          : "No"
        : answer.value.length > 0
          ? answer.value
          : "(left blank)";
    return `**${label}**\n${value}`;
  });
  const attachments = submission.files.length
    ? [
        [
          "**Attached files**",
          ...submission.files.map(
            (file) =>
              `- \`$BB_THREAD_STORAGE/${file.path}\` (${file.name}, ${file.sizeBytes} bytes)`,
          ),
          "Read them from thread storage with your normal tools.",
        ].join("\n"),
      ]
    : [];
  return [
    `The user answered the form on your Thread Page — ${heading}.`,
    ...fields,
    ...attachments,
  ].join("\n\n");
}

export function formatThreadReplyMessage(
  title: string | undefined,
  result: unknown,
): string {
  const heading = title?.trim() || "Interactive response";
  const serialized = JSON.stringify(result, null, 2) ?? "null";
  let longestBacktickRun = 0;
  for (const match of serialized.matchAll(/`+/g)) {
    longestBacktickRun = Math.max(longestBacktickRun, match[0].length);
  }
  const fence = "`".repeat(Math.max(3, longestBacktickRun + 1));
  return [
    `The user sent an interactive response from your Thread Page — ${heading}.`,
    `**Result**\n\n${fence}json\n${serialized}\n${fence}`,
  ].join("\n\n");
}

export function parseSubmission(value: unknown): Submission | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const input = value as Record<string, unknown>;
  if (
    typeof input.actionToken !== "string" ||
    input.actionToken.length > 4096 ||
    typeof input.submissionId !== "string" ||
    !/^[A-Za-z0-9._-]{1,128}$/.test(input.submissionId) ||
    typeof input.pageHash !== "string" ||
    !/^[a-f0-9]{64}$/.test(input.pageHash) ||
    typeof input.title !== "string" ||
    input.title.length > 300 ||
    !Array.isArray(input.answers) ||
    input.answers.length > 64
  ) {
    return null;
  }

  let total = input.title.length;
  const answers: FormAnswer[] = [];
  for (const raw of input.answers) {
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
    const answer = raw as Record<string, unknown>;
    if (
      typeof answer.name !== "string" ||
      answer.name.length > 128 ||
      typeof answer.label !== "string" ||
      answer.label.length > 300 ||
      !isAnswerValue(answer.value)
    ) {
      return null;
    }
    const valueLength = Array.isArray(answer.value)
      ? answer.value.reduce((sum, item) => sum + item.length, 0)
      : typeof answer.value === "string"
        ? answer.value.length
        : 1;
    total += answer.name.length + answer.label.length + valueLength;
    if (total > 32_000) return null;
    answers.push({
      name: answer.name,
      label: answer.label,
      value: answer.value,
    });
  }

  const files: SubmissionFile[] = [];
  if (input.files !== undefined) {
    if (!Array.isArray(input.files) || input.files.length > 8) return null;
    for (const raw of input.files) {
      if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
      const file = raw as Record<string, unknown>;
      if (
        typeof file.field !== "string" ||
        file.field.length > 128 ||
        typeof file.name !== "string" ||
        file.name.length > 80 ||
        file.name !== safeUploadName(file.name) ||
        typeof file.path !== "string" ||
        file.path.length > 300 ||
        !file.path.startsWith(`${UPLOAD_DIRNAME}/`) ||
        file.path.includes("..") ||
        typeof file.sizeBytes !== "number" ||
        !Number.isSafeInteger(file.sizeBytes) ||
        file.sizeBytes < 0 ||
        file.sizeBytes > MAX_UPLOAD_BYTES
      ) {
        return null;
      }
      files.push({
        field: file.field,
        name: file.name,
        path: file.path,
        sizeBytes: file.sizeBytes,
      });
    }
  }

  return {
    actionToken: input.actionToken,
    submissionId: input.submissionId,
    pageHash: input.pageHash,
    title: input.title,
    answers,
    files,
  };
}

function isAnswerValue(value: unknown): value is FormAnswerValue {
  if (typeof value === "boolean") return true;
  if (typeof value === "string") return value.length <= 8_000;
  return (
    Array.isArray(value) &&
    value.length <= 64 &&
    value.every((item) => typeof item === "string" && item.length <= 2_000)
  );
}
