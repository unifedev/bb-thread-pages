export const CONFIRMATION_TTL_MS = 2 * 60 * 1000;

/**
 * A signed challenge for one confirmed capability call.
 *
 * The server mints it, the trusted outer shell shows its summary and mints
 * nothing itself, and the server re-checks the signature before acting. The
 * untrusted page never authors the summary and cannot forge or replay a
 * challenge: it is bound to one request id, method, parameter fingerprint,
 * page revision, and thread, and it expires quickly.
 */
export interface ConfirmationChallengePayload {
  v: 2;
  scope: "confirm";
  threadId: string;
  pageHash: string;
  requestId: string;
  method: string;
  paramsHash: string;
  summary: string;
  iat: number;
  exp: number;
}

export function signConfirmationChallenge(
  payload: ConfirmationChallengePayload,
  key: Uint8Array,
): string {
  const encoded = encodeJson(payload);
  const signature = createHmac("sha256", key)
    .update(encoded, "ascii")
    .digest("base64url");
  return `${encoded}.${signature}`;
}

function isConfirmationChallenge(
  value: unknown,
  now: number,
): value is ConfirmationChallengePayload {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const payload = value as Record<string, unknown>;
  return (
    payload.v === 2 &&
    payload.scope === "confirm" &&
    typeof payload.threadId === "string" &&
    /^[A-Za-z0-9_-]{3,128}$/.test(payload.threadId) &&
    typeof payload.pageHash === "string" &&
    /^[a-f0-9]{64}$/.test(payload.pageHash) &&
    typeof payload.requestId === "string" &&
    payload.requestId.length > 0 &&
    payload.requestId.length <= 96 &&
    typeof payload.method === "string" &&
    payload.method.length > 0 &&
    payload.method.length <= 96 &&
    typeof payload.paramsHash === "string" &&
    /^[a-f0-9]{64}$/.test(payload.paramsHash) &&
    typeof payload.summary === "string" &&
    payload.summary.length > 0 &&
    payload.summary.length <= 512 &&
    typeof payload.iat === "number" &&
    Number.isSafeInteger(payload.iat) &&
    typeof payload.exp === "number" &&
    Number.isSafeInteger(payload.exp) &&
    payload.iat <= now + 30_000 &&
    payload.exp > now &&
    payload.exp > payload.iat &&
    payload.exp - payload.iat <= CONFIRMATION_TTL_MS
  );
}

export function verifyConfirmationChallenge(
  token: string,
  key: Uint8Array,
  now = Date.now(),
): ConfirmationChallengePayload | null {
  const parts = token.split(".");
  if (parts.length !== 2 || !parts[0] || !parts[1]) return null;
  const [encoded, suppliedSignature] = parts;
  try {
    const expected = createHmac("sha256", key)
      .update(encoded, "ascii")
      .digest();
    const supplied = Buffer.from(suppliedSignature, "base64url");
    if (supplied.byteLength !== expected.byteLength) return null;
    if (supplied.toString("base64url") !== suppliedSignature) return null;
    if (!timingSafeEqual(supplied, expected)) return null;
    const decoded = JSON.parse(
      Buffer.from(encoded, "base64url").toString("utf8"),
    ) as unknown;
    return isConfirmationChallenge(decoded, now) ? decoded : null;
  } catch {
    return null;
  }
}

