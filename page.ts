interface AuthoredDocument {
  document: HtmlDocument;
  injectionParent: HtmlElement;
}

function directHtmlChild(
  parent: HtmlDocument | HtmlElement,
  tagName: string,
): HtmlElement | null {
  for (const child of parent.childNodes) {
    if (
      defaultTreeAdapter.isElementNode(child) &&
      child.tagName === tagName &&
      child.namespaceURI === "http://www.w3.org/1999/xhtml"
    ) {
      return child;
    }
  }
  return null;
}

function parseAuthoredDocument(source: string): AuthoredDocument | null {
  // A BOM at the beginning of an HTML byte stream is an encoding signature,
  // not a text node. parse5 accepts strings, so remove it before tokenization.
  const browserSource = source.charCodeAt(0) === 0xfeff ? source.slice(1) : source;
  const document = parseHtml(browserSource, {
    scriptingEnabled: true,
    sourceCodeLocationInfo: true,
  });
  const html = directHtmlChild(document, "html");
  if (!html) return null;

  const head = directHtmlChild(html, "head");
  const body = directHtmlChild(html, "body");
  const frameset = directHtmlChild(html, "frameset");
  const hasHtmlDoctype = document.childNodes.some(
    (child) =>
      defaultTreeAdapter.isDocumentTypeNode(child) &&
      child.name.toLowerCase() === "html",
  );
  const hasAuthoredShell = [html, head, body, frameset].some(
    (element) => element?.sourceCodeLocation != null,
  );

  if (!hasHtmlDoctype && !hasAuthoredShell) return null;
  return { document, injectionParent: head ?? body ?? frameset ?? html };
}

function injectKernel(
  authored: AuthoredDocument,
  runtime: string,
  nonce: string,
  assetBase?: string | null,
): string {
  const script = defaultTreeAdapter.createElement(
    "script",
    authored.injectionParent.namespaceURI,
    [
      { name: "data-thread-page-kernel", value: "" },
      { name: "nonce", value: nonce },
    ],
  );
  defaultTreeAdapter.insertText(script, runtime);

  // The first <base> in a document wins, so the confined asset preview is
  // injected ahead of any authored one. Relative page resources therefore
  // resolve inside the thread's asset directory and nowhere else.
  const nodes = assetBase
    ? [
        defaultTreeAdapter.createElement(
          "base",
          authored.injectionParent.namespaceURI,
          [{ name: "href", value: assetBase }],
        ),
        script,
      ]
    : [script];

  // Insert in order at the very front of the injection parent.
  const anchor = defaultTreeAdapter.getFirstChild(authored.injectionParent);
  for (const node of nodes) {
    if (anchor) {
      defaultTreeAdapter.insertBefore(authored.injectionParent, node, anchor);
    } else {
      defaultTreeAdapter.appendChild(authored.injectionParent, node);
    }
  }

  return serializeHtml(authored.document);
}

export function renderDocument(options: {
  fragment: string;
  nonce: string;
  pageHash: string;
  stale: boolean;
  assetBase?: string | null;
}): string {
  const config = jsonForInlineScript({
    pageRevision: options.pageHash,
    stale: options.stale,
    assetBase: options.assetBase ?? null,
  });
  const runtime = DOCUMENT_RUNTIME.replace("__THREAD_PAGE_CONFIG__", config);
  const kernel = `<script data-thread-page-kernel nonce="${escapeHtml(options.nonce)}">${runtime}</script>`;

  const authoredDocument = parseAuthoredDocument(options.fragment);
  if (authoredDocument) {
    return injectKernel(
      authoredDocument,
      runtime,
      options.nonce,
      options.assetBase,
    );
  }

  const staleBanner = options.stale
    ? '<aside class="stale" data-thread-page-offline="plugin" role="status"><strong>Offline copy.</strong> The source host is unavailable. This cached page is read-only until it reconnects.</aside>'
    : "";

  const base = options.assetBase
    ? `<base href="${escapeHtml(options.assetBase)}">\n`
    : "";

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="color-scheme" content="light dark">
<title>Thread Page</title>
${base}<style nonce="${escapeHtml(options.nonce)}">${DOCUMENT_CSS}</style>
${kernel}
</head>
<body>
<div class="thread-page">${staleBanner}${options.fragment}</div>
</body>
</html>`;
}

